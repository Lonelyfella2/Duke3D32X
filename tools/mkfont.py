#!/usr/bin/env python3
"""
mkfont.py - convert assets/font.png (16x6 grid of 9x8 cells, ASCII 32..127)
into gen/font8x8.h for the in-game text renderer.

Each glyph pixel keeps its role in the original art so the game can recolour
the font while preserving the bevel:
    0 = clear, 1 = shadow, 2 = body, 3 = highlight
The source colours are matched to the nearest of the font's own four inks
(navy shadow, blue body, cyan highlight, white -> body).  Glyph widths are
measured so text is drawn proportionally.

Usage: mkfont.py assets/font.png gen/font8x8.h
"""
import sys

from PIL import Image

CELL_W, CELL_H, COLS, FIRST, COUNT = 9, 8, 16, 32, 96
INKS = {                       # RGB -> role
    (32, 32, 66): 1,           # shadow
    (66, 82, 138): 2,          # body
    (95, 205, 228): 3,         # highlight
    (255, 255, 255): 2,        # the odd white glyph ('&') -> body
}
SPACE_ADV = 6
EMPTY_ADV = 4


def role(rgba):
    r, g, b, a = rgba
    if a < 128:
        return 0
    if (r, g, b) in INKS:
        return INKS[(r, g, b)]
    # nearest ink for anything unexpected
    best = min(INKS, key=lambda k: (k[0] - r) ** 2 + (k[1] - g) ** 2 + (k[2] - b) ** 2)
    return INKS[best]


def main():
    src, dst = sys.argv[1], sys.argv[2]
    im = Image.open(src).convert("RGBA")
    if im.size != (CELL_W * COLS, CELL_H * (COUNT // COLS)):
        raise SystemExit(f"{src}: expected {CELL_W * COLS}x{CELL_H * (COUNT // COLS)}, got {im.size}")
    px = im.load()
    rows, adv = [], []
    for i in range(COUNT):
        cx, cy = (i % COLS) * CELL_W, (i // COLS) * CELL_H
        glyph = []
        right = -1
        for y in range(CELL_H):
            v = 0
            for x in range(CELL_W):
                k = role(px[cx + x, cy + y])
                if k:
                    right = max(right, x)
                v |= k << (2 * x)              # column x at bits 2x..2x+1
            glyph.append(v)
        ch = FIRST + i
        if ch == 32:
            a = SPACE_ADV
        elif right < 0:
            a = EMPTY_ADV                      # glyph not drawn in the sheet
        else:
            a = right + 2                      # width + 1 px gap
        rows.append(glyph)
        adv.append(a)
    # ';' is blank in the sheet: build it from ':' (top) and ',' (bottom)
    colon, comma, semi = ord(":") - FIRST, ord(",") - FIRST, ord(";") - FIRST
    if not any(rows[semi]):
        rows[semi] = rows[colon][:5] + rows[comma][5:]
        adv[semi] = max(adv[colon], adv[comma])
    with open(dst, "w") as f:
        f.write("/* generated by tools/mkfont.py from assets/font.png - do not edit */\n")
        f.write("#ifndef FONT8X8_H\n#define FONT8X8_H\n#include <stdint.h>\n\n")
        f.write(f"#define FONT_FIRST {FIRST}\n#define FONT_COUNT {COUNT}\n#define FONT_H {CELL_H}\n")
        f.write(f"#define FONT_W {CELL_W}\n\n")
        f.write("/* 2 bits per pixel, column x at bits 2x..2x+1:\n"
                " * 0 clear, 1 shadow, 2 body, 3 highlight */\n")
        f.write(f"static const uint32_t font_rows[{COUNT}][{CELL_H}] = {{\n")
        for i, g in enumerate(rows):
            c = chr(FIRST + i)
            label = c if c not in "\\*/" and 32 < ord(c) < 127 else f"0x{ord(c):02x}"
            f.write("    { " + ", ".join(f"0x{v:05x}" for v in g) + " },  /* " + label + " */\n")
        f.write("};\n\n")
        f.write(f"static const uint8_t font_adv[{COUNT}] = {{\n")
        for i in range(0, COUNT, 16):
            f.write("    " + ", ".join(str(a) for a in adv[i:i + 16]) + ",\n")
        f.write("};\n\n#endif\n")
    print(f"mkfont: {COUNT} glyphs -> {dst}")


if __name__ == "__main__":
    main()
